 const same=await db.rpc('media_save_photo',{...request,board_id:boardA,source_author_id:USERS.stranger});
 assert.equal(same.id,saved.id);
 await db.rpc('media_link_keep',{...actor('follower'),keep_id:saved.id,board_id:boardB});
 assert.equal(await db.sql(`SELECT count(*) FROM private.photo_keeps WHERE source_item_id='${source.items[0]}'`),'1');
