 console.log('PASS: canonical Keep links to two Boards without extra media objects or forged creator IDs');
 await db.sql(`UPDATE public.dumps SET created_at=clock_timestamp()-interval '25 hours',allow_others_to_keep=false WHERE id='${source.id}'; DELETE FROM public.follows WHERE follower_id='${USERS.follower}' AND following_id='${USERS.owner}';`);
 assert.ok((await db.rpc('media_keep_frame',{...actor('follower'),keep_id:saved.id})).path);
 const listed=await db.rpc('media_list_keeps',actor('follower'));assert.equal(listed[0].id,saved.id);
 await db.sql(`UPDATE public.profiles SET username='renamed-local-author' WHERE id='${USERS.owner}'`);
 assert.equal((await db.rpc('media_list_keeps',actor('follower')))[0].source_username,'renamed-local-author');
 console.log('PASS: expiry, disabled Keep and unfollow preserve grants; creator grouping uses UUID/current username');
 await assert.rejects(db.rpc('media_save_photo',{...request,item_position:1}),/keep_forbidden/);
 await db.sql(`INSERT INTO private.account_blocks VALUES('${USERS.owner}','${USERS.follower}')`);
 await assert.rejects(db.rpc('media_keep_frame',{...actor('follower'),keep_id:saved.id}),/keep_forbidden/);
 assert.deepEqual(await db.rpc('media_list_keeps',actor('follower')),[]);
 await db.sql('DELETE FROM private.account_blocks');
 assert.ok((await db.rpc('media_keep_frame',{...actor('follower'),keep_id:saved.id})).path);
 console.log('PASS: expired new saves denied; blocking suspends existing access and unblock restores only the existing grant');
 await db.rpc('media_remove_board_photo',{...actor('follower'),keep_id:saved.id,board_id:boardA});
 await assert.rejects(db.rpc('media_remove_keep',{...actor('follower'),keep_id:saved.id}),/keep_still_organized/);
 assert.equal(await db.sql(`SELECT count(*) FROM public.boards WHERE id='${boardA}'`),'1');
 console.log('PASS: per-photo Board removal preserves Board, other membership and canonical grant');
 const ownerPost=await seedOnce(db,USERS.owner,'24h');
 await db.sql(`UPDATE public.dumps SET allow_others_to_keep=false WHERE id='${ownerPost.id}'`);
 assert.equal((await db.rpc('media_save_photo',{...actor('owner'),dump_id:ownerPost.id,item_position:0})).source_author_id,USERS.owner);
 await assert.rejects(db.rpc('media_save_photo',{...actor('follower'),dump_id:ownerPost.id,item_position:0}),/keep_forbidden/);
 const once=await seedOnce(db,USERS.owner);
 await assert.rejects(db.rpc('media_save_photo',{...actor('owner'),dump_id:once.id,item_position:0}),/keep_forbidden/);
 console.log('PASS: own 24-hour photos bypass only Keep toggle; View Once remains non-Keepable including owner shortcut');
 assert.ok((await db.rpc('media_owner_frame',{...actor('owner'),item_id:once.items[0]})).path);
 await assert.rejects(db.rpc('media_owner_frame',{...actor('follower'),item_id:once.items[0]}),/media_forbidden/);
 console.log('PASS: legitimate owner management is separate from a non-owner viewer entitlement');
 const owned=await db.rpc('media_owner_archive',actor('owner'));
 assert.ok(owned.some(row=>row.id===once.id));assert.ok(owned.every(row=>row.user_id===USERS.owner));
 const foreign=await db.rpc('media_owner_archive',actor('follower'));
 assert.ok(foreign.every(row=>row.user_id===USERS.follower));assert.equal(JSON.stringify(owned).includes('image_path'),false);
 console.log('PASS: owner management listing exposes no foreign assets or raw Storage paths');
 await db.sql(`UPDATE public.dumps SET created_at=clock_timestamp()-interval '25 hours' WHERE id='${ownerPost.id}'`);
 assert.equal((await db.rpc('media_save_photo',{...actor('owner'),dump_id:ownerPost.id,item_position:1})).source_item_id,ownerPost.items[1]);
 console.log('PASS: owner can organize an archived own 24-hour photo; this does not grant another user a new expired Keep');
 await db.sql(`DELETE FROM public.dump_items WHERE id='${source.items[0]}'`);
 await assert.rejects(db.rpc('media_keep_frame',{...actor('follower'),keep_id:saved.id}),/keep_forbidden/);
 assert.equal(await db.sql(`SELECT count(*) FROM private.keep_board_memberships WHERE keep_id='${saved.id}'`),'0');
 assert.equal(await db.sql(`SELECT count(*) FROM private.media_cleanup_jobs WHERE name LIKE '%${source.id}/0.png'`),'1');
 const raw=await db.sql(`SET ROLE authenticated; SELECT set_config('request.jwt.claim.sub','${USERS.owner}',false); SELECT count(*) FROM storage.objects WHERE name LIKE '%${source.id}/0.png';`);
 assert.equal(raw.split(/\r?\n/).at(-1),'0');
 console.log('PASS: photo deletion atomically cascades all grants/memberships and prevents direct Storage reads before cleanup');
 const worker=randomUUID();
 const jobs=await db.rpc('media_lease_cleanup',{worker_id:worker});assert.equal(jobs.length,1);
 await db.rpc('media_fail_cleanup',{job_id:jobs[0].id,lease_token:jobs[0].lease_token});
 assert.equal(await db.sql(`SELECT status FROM private.media_cleanup_jobs WHERE id='${jobs[0].id}'`),'pending');
 await db.sql(`UPDATE private.media_cleanup_jobs SET next_attempt_at=clock_timestamp()-interval '1 second'`);
 const retry=(await db.rpc('media_lease_cleanup',{worker_id:worker}))[0];
 assert.notEqual(retry.lease_token,jobs[0].lease_token);
 assert.equal((await db.rpc('media_finish_cleanup',{job_id:retry.id,lease_token:jobs[0].lease_token})).completed,false);
 await db.sql(`DELETE FROM storage.objects WHERE name='${retry.name}'`);
 assert.equal((await db.rpc('media_finish_cleanup',{job_id:retry.id,lease_token:retry.lease_token})).completed,true);
 await db.sql(`INSERT INTO storage.objects(bucket_id,name) VALUES('${retry.bucket_id}','${retry.name}')`);
 await db.rpc('media_reconcile_cleanup',{});
 assert.equal(await db.sql(`SELECT status FROM private.media_cleanup_jobs WHERE id='${retry.id}'`),'pending');
 console.log('PASS: cleanup retries safely, rejects stale worker completion, and reconciles late uploads after apparent success');
 await assert.rejects(db.sql(`SET ROLE authenticated; INSERT INTO public.board_items(id,user_id,dump_id,item_position) VALUES('${randomUUID()}','${USERS.follower}','${once.id}',0)`),/permission denied/);
 console.log('PASS: legacy direct Board writes cannot bypass canonical Keep authorization');
 const shared=await seedOnce(db,USERS.stranger,'24h');
 const keptA=await db.rpc('media_save_photo',{...actor('owner'),dump_id:shared.id,item_position:0});
 const keptB=await db.rpc('media_save_photo',{...actor('follower'),dump_id:shared.id,item_position:0});
 await db.sql(`UPDATE public.profiles SET is_private=true WHERE id='${USERS.stranger}'; UPDATE public.dumps SET allow_others_to_keep=false,created_at=clock_timestamp()-interval '25 hours' WHERE id='${shared.id}'`);
 assert.ok((await db.rpc('media_keep_frame',{...actor('follower'),keep_id:keptB.id})).path);
 await assert.rejects(db.rpc('media_save_photo',{...actor('follower'),dump_id:shared.id,item_position:1}),/keep_forbidden/);
 console.log('PASS: switching a public creator private stops new grants but preserves previously authorized Keeps');
 await db.rpc('media_remove_keep',{...actor('owner'),keep_id:keptA.id});
 assert.ok((await db.rpc('media_keep_frame',{...actor('follower'),keep_id:keptB.id})).path);
 console.log('PASS: removing one saver grant cannot delete another saver grant or the shared source');
 await assert.rejects(db.sql(`UPDATE public.dump_items SET image_path='${USERS.stranger}/replacement.png' WHERE id='${shared.items[0]}'`),/immutable_source_photo/);
 await assert.rejects(db.sql(`UPDATE public.dumps SET expiry='once' WHERE id='${shared.id}'`),/immutable_post_media_mode/);
 console.log('PASS: source identity and post media mode cannot be retargeted behind existing grants');
 // Rollback is exercised on one real connection, not across unrelated psql sessions.
 const rollback=await db.sql(`BEGIN; DELETE FROM public.dump_items WHERE id='${shared.items[0]}'; ROLLBACK; SELECT count(*) FROM private.photo_keeps WHERE id='${keptB.id}';`);
 assert.equal(rollback.split(/\r?\n/).at(-1),'1');
 assert.equal(await db.sql(`SELECT count(*) FROM private.media_cleanup_jobs WHERE name LIKE '%${shared.id}%'`),'0');
 await db.sql(`DELETE FROM public.dumps WHERE id='${shared.id}'`);
 await assert.rejects(db.rpc('media_keep_frame',{...actor('follower'),keep_id:keptB.id}),/keep_forbidden/);
 assert.equal(await db.sql(`SELECT count(*) FROM private.media_cleanup_jobs WHERE name LIKE '%${shared.id}%'`),'2');
 console.log('PASS: deletion rollback preserves grants and leaves no jobs; committed whole-post deletion revokes every photo and queues both originals');
