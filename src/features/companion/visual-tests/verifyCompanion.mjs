import { mkdtemp, mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { join } from "node:path";
import assert from "node:assert/strict";
import { withCompanionBrowser } from "./browserHarness.mjs";
import { runIntegrationChecks } from "./integrationChecks.mjs";
import { runInteractionChecks } from "./interactionChecks.mjs";

const directory = "src/features/companion/visual-tests";
// Always create a new run; never replace approved or historical evidence.
await mkdir(join(directory, "runs"), { recursive: true });
const output = await mkdtemp(join(directory, "runs", process.argv.includes("--art-only") ? "art-" : "browser-"));
const manifest = JSON.parse(await readFile(join(directory, "approved-manifest.json"), "utf8"));
for (const [path, hash] of Object.entries(manifest)) assert.equal(createHash("sha256").update(await readFile(path)).digest("hex"), hash, `Approved artifact changed: ${path}`);
const report = { rasterCases: [], checks: ["Approved prototype evidence and original body sheet hashes unchanged"], screenshots: [] };
report.stylesheetMode = process.env.COMPANION_BUILT_CSS ? "actual production-build CSS (external font import omitted)" : "application source CSS";
await mkdir(output, { recursive: true });
await withCompanionBrowser(async ({ cdp, evaluate, screenshot }) => {
  report.rasterCases = await evaluate("window.runCompanionRasterChecks()");
  assert.equal(report.rasterCases.length, 264);
  assert(report.rasterCases.every((item) => item.passed), JSON.stringify(report.rasterCases.filter((item) => !item.passed)));
  report.checks.push("264/264 unique costume/season/frame rasters: generated sheet equality, torso containment, protected ear/eye/muzzle/feet, sharp clothing edges");
  report.checks.push("36/36 approved Superhero/Santa/Witch reference frames match pixel-for-pixel; Everyday neutral art is unchanged");
  if (process.argv.includes("--art-only")) return;
  const currentSource = await evaluate("getComputedStyle(document.querySelector('.capybara-pixel-sprite')).backgroundImage");
  assert(currentSource.includes("companion-fitted-sprite.svg"), "Live renderer still uses the old sprite sheet");
  report.integrationCases = await runIntegrationChecks({ cdp, evaluate });
  report.interactions = await runInteractionChecks({ cdp, evaluate });
  await cdp("Emulation.setDeviceMetricsOverride", { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  await evaluate("window.companionQA.setDirection('right');window.companionQA.setTab('comparison');scrollTo(0,0)");
  await evaluate("new Promise(resolve => setTimeout(resolve, 300))");
  await screenshot(join(output, "legacy-vs-integrated-right.png")); report.screenshots.push("legacy-vs-integrated-right.png");
  await evaluate("window.companionQA.setDirection('left')");
  await evaluate("new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))");
  await screenshot(join(output, "legacy-vs-integrated-left.png")); report.screenshots.push("legacy-vs-integrated-left.png");
  await evaluate("window.companionQA.setDirection('right')");
  await evaluate("window.companionQA.setTab('gallery')");
  await evaluate("new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))");
  await screenshot(join(output, "all-costumes-right.png")); report.screenshots.push("all-costumes-right.png");
  await evaluate("window.companionQA.setDirection('left')");
  await evaluate("new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))");
  await screenshot(join(output, "all-costumes-left.png")); report.screenshots.push("all-costumes-left.png");
  await cdp("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 2, mobile: true });
  assert(await evaluate("document.documentElement.scrollWidth <= innerWidth"), "Mobile gallery overflows");
  await evaluate("window.companionQA.setTab('settings');window.companionQA.setValue({enabled:true,name:'Buddy',costume:'hero',animation:'sit',reactions:true});scrollTo(0,0)");
  await evaluate("new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))");
  assert(await evaluate("document.documentElement.scrollWidth <= innerWidth"), "Mobile Settings overflows");
  await evaluate("new Promise(resolve => setTimeout(resolve, 1700))");
  await screenshot(join(output, "settings-mobile.png")); report.screenshots.push("settings-mobile.png");
  await cdp("Emulation.setDeviceMetricsOverride", { width: 320, height: 844, deviceScaleFactor: 1, mobile: true });
  await evaluate("new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))");
  await screenshot(join(output, "settings-320px.png")); report.screenshots.push("settings-320px.png");
  await cdp("Emulation.setDeviceMetricsOverride", { width: 390, height: 844, deviceScaleFactor: 2, mobile: true });
  await cdp("Emulation.setEmulatedMedia", { features: [{ name: "prefers-reduced-motion", value: "reduce" }] });
  await evaluate("new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))");
  await screenshot(join(output, "settings-mobile-reduced-motion.png")); report.screenshots.push("settings-mobile-reduced-motion.png");
  report.checks.push("Both directions and mobile gallery/actual Settings captured without horizontal document overflow");
});
await writeFile(join(output, "browser-results.json"), JSON.stringify(report, null, 2) + "\n", { flag: "wx" });
console.log(JSON.stringify({ output, cases: report.rasterCases.length, checks: report.checks, screenshots: report.screenshots }, null, 2));
